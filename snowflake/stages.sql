-- External stages over both landing zones. Run as ACCOUNTADMIN once per environment,
-- then hand the DESC INTEGRATION values to Terraform (AWS trust policy / Azure consent).

CREATE STORAGE INTEGRATION IF NOT EXISTS AWS_LANDING_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<terraform output snowflake_role_arn>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://acme-loans-landing-prod/raw/');

CREATE STORAGE INTEGRATION IF NOT EXISTS AZURE_LANDING_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'AZURE'
  ENABLED = TRUE
  AZURE_TENANT_ID = '<tenant id>'
  STORAGE_ALLOWED_LOCATIONS = ('azure://acmeloanslakeprod.blob.core.windows.net/landing/raw/');

-- DESC INTEGRATION AWS_LANDING_INT;    -> STORAGE_AWS_IAM_USER_ARN, STORAGE_AWS_EXTERNAL_ID
-- DESC INTEGRATION AZURE_LANDING_INT;  -> AZURE_CONSENT_URL (open it), AZURE_MULTI_TENANT_APP_NAME

GRANT USAGE ON INTEGRATION AWS_LANDING_INT   TO ROLE LOANS_LOADER;
GRANT USAGE ON INTEGRATION AZURE_LANDING_INT TO ROLE LOANS_LOADER;

USE ROLE LOANS_LOADER;
CREATE SCHEMA IF NOT EXISTS LOANS.RAW;

CREATE STAGE IF NOT EXISTS LOANS.RAW.AWS_LANDING
  STORAGE_INTEGRATION = AWS_LANDING_INT
  URL = 's3://acme-loans-landing-prod/raw/'
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE);

CREATE STAGE IF NOT EXISTS LOANS.RAW.AZURE_LANDING
  STORAGE_INTEGRATION = AZURE_LANDING_INT
  URL = 'azure://acmeloanslakeprod.blob.core.windows.net/landing/raw/'
  FILE_FORMAT = (TYPE = PARQUET USE_LOGICAL_TYPE = TRUE);

